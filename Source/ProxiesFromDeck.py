### Print Tweaking - these can be adjusted to your preference, but generally a slight boost in saturation/brightness/contrast helps make the images pop when printed on matte media. Adjust as needed or set to 1.0 for no change.
SATURATION = 1.00 
BRIGHTNESS = 1.00  
CONTRAST = 1.0

### Get image from URL with caching and upscale to target print resolution
def get_image(url):
    with image_cache_lock:
        cached = image_cache.get(url)
    if cached is not None:
        return cached

    r = image_session.get(url, timeout=20)
    img = Image.open(BytesIO(r.content)).convert("RGB")

    # Upscale to target print resolution
    img = img.resize((TARGET_W, TARGET_H), Image.LANCZOS)

    img = ImageEnhance.Color(img).enhance(SATURATION)
    img = ImageEnhance.Brightness(img).enhance(BRIGHTNESS)
    img = ImageEnhance.Contrast(img).enhance(CONTRAST)
    img = adjust_gamma(img, 0.92)

    img = img.filter(
        ImageFilter.UnsharpMask(
            radius=0.5,
            percent=120,
            threshold=2
        )
    )

    with image_cache_lock:
        image_cache[url] = img

    return img

### Get ImageReader for ReportLab with caching
def get_image_reader(url):
    with image_reader_cache_lock:
        cached = image_reader_cache.get(url)
    if cached is not None:
        return cached

    img = get_image(url)
    reader = ImageReader(img)
    with image_reader_cache_lock:
        image_reader_cache[url] = reader
    return reader

### Adjusts gamma
def adjust_gamma(img, gamma=0.92):
    inv = 1.0 / gamma

    table = [
        ((i / 255.0) ** inv) * 255
        for i in range(256)
    ]

    return img.point(table * 3)

### Parse a line of the decklist - expects format like "4 Pikachu BWP 25"
def parse_line(line):
    line = line.strip()

    if not line:
        return None

    m = re.match(r"^(\d+)\s+(.+?)\s+([A-Z0-9]+)\s+([A-Z0-9]+)$", line)

    if not m:
        return None

    count = int(m.group(1))
    name = m.group(2).strip()
    set_code = m.group(3).strip()
    number = m.group(4).strip()

    return count, name, set_code, number

### Normalize card name for API queries - convert stars to symbols and energy letters to {L}, {W}, etc. to maximize chances of matching weird card names in the API
def normalize_name_for_api(name):
    name = re.sub(r"\bprism\s*star\b", "◇", name, flags=re.IGNORECASE)
    name = re.sub(r"\bstar\b", "★", name, flags=re.IGNORECASE)

    def replace_energy(match):
        letters = match.group(1)
        return " ".join(f"{{{c}}}" for c in letters)

    # ONLY convert trailing energy letters for Unit/Blend Energy cards
    if re.search(r"\b(unit|blend)\s+energy\b", name, re.IGNORECASE):
        name = re.sub(r"\b([LWMFPDC]+)\b$", replace_energy, name)

    name = re.sub(r"\s+", " ", name).strip()
    return name

### Normalize text for matching - remove accents, lowercase, and normalize stars to maximize chances of matching weird card names in the API
def norm(text):
    text = text.lower()

    text = text.replace("★", "star")
    text = text.replace("◇", "prism star")

    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))

    # strip punctuation
    text = re.sub(r"[^a-z0-9\s]", "", text)

    text = re.sub(r"\s+", " ", text).strip()

    return text

### Build a unique lookup key for a card based on normalized name, number, and set code
def make_lookup_key(name, number, set_code):
    return (norm(name), str(number).upper().strip(), str(set_code).upper().strip())

### Build a unique set of cards from the decklist, keyed by normalized name + number + set code to minimize API calls
def build_unique(deck_lines):
    unique = {}
    counts = {}

    for line in deck_lines:
        parsed = parse_line(line)
        if not parsed:
            continue

        count, name, set_code, number = parsed
        key = make_lookup_key(name, number, set_code)

        if key not in unique:
            unique[key] = {
                "name": name,
                "number": number,
                "set_code": set_code.upper()
            }
            counts[key] = 0

        counts[key] += count

    return unique, counts

### Build possible number variants based on set code and original number, to maximize chances of matching weird promo numbering schemes
### (Limitless/TGCLive uses different numbering sometimes so this hopefully catches those)
def build_possible_numbers(number, set_code):
    number = str(number).upper().strip()
    nums = {number}

    try:
        n_int = int(number)
    except:
        n_int = None

    if set_code == "BWP":
        if n_int is not None:
            nums.update({
                f"BW{n_int}",
                f"BW{n_int:02d}",
                str(n_int)
            })

    elif set_code == "XYP":
        if n_int is not None:
            nums.update({
                f"XY{n_int}",
                f"XY{n_int:02d}",
                str(n_int)
            })

    elif set_code == "SMP":
        if n_int is not None:
            nums.update({
                f"SM{n_int}",
                f"SM{n_int:02d}",
                str(n_int)
            })
    elif set_code == "WP":
        if n_int is not None:
            nums.update({
                f"WP{n_int}",
                f"WP{n_int:02d}",
                str(n_int)
            })

    # General fallback for weird promos
    if n_int is not None:
        nums.add(str(n_int))
        cleaned_set_code = re.sub(r"[^A-Z]", "", set_code.upper())
        if cleaned_set_code:
            nums.update({
                f"{cleaned_set_code}{n_int}",
                f"{cleaned_set_code}{n_int:02d}"
            })


    return nums

### Strip bracketed suffixes from a card name for query fallback handling
### Example: "Ancient Technical Machine [Rock]" -> "Ancient Technical Machine"
def strip_bracket_suffix(name):
    return re.sub(r"\s*\[[^\]]+\]\s*$", "", name).strip()

### Build normalized aliases for names so cards can still be matched when punctuation,
### symbols, or alternate suffixes are used in the decklist or API data.
def build_name_aliases(name):
    if not name:
        return []

    raw = str(name).strip()
    aliases = []

    if raw:
        aliases.append(raw)

    lowered = raw.lower()
    if lowered:
        aliases.append(lowered)

    normalized = re.sub(r"[^a-z0-9]+", " ", lowered).strip()
    normalized = re.sub(r"\s+", " ", normalized)
    if normalized:
        aliases.append(normalized)

    compact = re.sub(r"[^a-z0-9]+", "", lowered)
    if compact:
        aliases.append(compact)

    apostrophe_safe = re.sub(r"['’]", "", lowered)
    apostrophe_safe = re.sub(r"[^a-z0-9]+", " ", apostrophe_safe).strip()
    apostrophe_safe = re.sub(r"\s+", " ", apostrophe_safe)
    if apostrophe_safe:
        aliases.append(apostrophe_safe)

    apostrophe_compact = re.sub(r"['’]", "", lowered)
    apostrophe_compact = re.sub(r"[^a-z0-9]+", "", apostrophe_compact)
    if apostrophe_compact:
        aliases.append(apostrophe_compact)

    for suffix in [" ex", " gx", " legend", " star", " prism star", " lv x", " lv.x", " g", " v"]:
        if suffix in lowered:
            without_suffix = lowered.replace(suffix, " ").strip()
            if without_suffix:
                aliases.append(without_suffix)
                aliases.append(re.sub(r"[^a-z0-9]+", " ", without_suffix).strip())
                aliases.append(re.sub(r"[^a-z0-9]+", "", without_suffix))

    seen = set()
    ordered = []
    for alias in aliases:
        alias = alias.strip()
        if alias and alias not in seen:
            seen.add(alias)
            ordered.append(alias)

    return ordered

### Build fallback name variants for cards that may be listed in alternate spellings
### or with special gender/symbol forms that the API requires.
def build_name_variants(api_name):
    variants = [api_name]
    bracket_safe = re.sub(r"[\[\]]", "", api_name).strip()
    if bracket_safe != api_name:
        variants.append(bracket_safe)

    stripped_name = strip_bracket_suffix(api_name)
    if stripped_name and stripped_name not in variants:
        variants.append(stripped_name)

    if re.search(r"\bNidoran\s*(?:F|Female)\b", api_name, flags=re.IGNORECASE):
        variants.append(re.sub(r"\bNidoran\s*(?:F|Female)\b", "Nidoran♀", api_name, flags=re.IGNORECASE))
    if re.search(r"\bNidoran\s*(?:M|Male)\b", api_name, flags=re.IGNORECASE):
        variants.append(re.sub(r"\bNidoran\s*(?:M|Male)\b", "Nidoran♂", api_name, flags=re.IGNORECASE))

    for alias in build_name_aliases(api_name):
        if alias not in variants:
            variants.append(alias)

    seen = set()
    ordered = []
    for v in variants:
        v = v.strip()
        if v and v not in seen:
            seen.add(v)
            ordered.append(v)

    return ordered

def build_card_lookup_for_set(set_code, page_size=100):
    set_code = str(set_code).upper().strip()
    with card_lookup_cache_lock:
        cached = card_lookup_cache.get(set_code)
        if cached is not None:
            return cached

    lookup = {}
    cards = []
    page = 1

    while True:
        try:
            results = Card.where(q=f"set.ptcgoCode:{set_code}", page=page, pageSize=page_size)
        except Exception:
            results = []

        if not results:
            break

        for card in results:
            if not getattr(card, "name", None):
                continue
            cards.append(card)
            key = make_lookup_key(card.name, getattr(card, "number", ""), set_code)
            if key not in lookup:
                lookup[key] = card

        if len(results) < page_size:
            break
        page += 1

    with card_lookup_cache_lock:
        card_lookup_cache[set_code] = (lookup, cards)

    return lookup, cards

### Deals with random escape characters in card names for API queries
def quote_value(value):
    return value.replace('\\', '\\\\').replace('"', '\\"')

### Fallback search for cards that may not be in the set-wide fetch, using a series of queries to maximize chances of finding a match
def find_fallback_cards(item, set_code):
    name = item["name"]
    number = item["number"]
    api_name = normalize_name_for_api(name)
    possible_numbers = sorted(build_possible_numbers(number, set_code), key=lambda v: (len(v), v))
    name_variants = build_name_variants(api_name)
    queries = []

    for num in possible_numbers:
        for variant in name_variants:
            quoted_variant = quote_value(variant)
            queries.append(f'name:"{quoted_variant}" number:{num}')
            queries.append(f'name:"{quoted_variant}"')
        queries.append(f'number:{num}')

    if ("unit energy" in norm(name) or "blend energy" in norm(name)) and not queries:
        base_name = "Unit Energy" if "unit energy" in norm(name) else "Blend Energy"
        queries.append(f'name:"{quote_value(base_name)}"')

    seen_ids = set()
    cards = []

    for q in queries:
        try:
            results_q = Card.where(q=q, pageSize=CARD_QUERY_PAGE_SIZE)
        except Exception:
            continue

        if not results_q:
            continue

        for c in results_q:
            if c.id not in seen_ids:
                seen_ids.add(c.id)
                cards.append(c)

        if cards:
            break

    return cards

### Fetch candidate cards from API for each unique item in the decklist, using a single set-wide fetch
### and only a small fallback path for misses.
def fetch_candidates(unique_items, max_workers=12):
    results = {}
    grouped_items = {}

    for item in unique_items.values():
        grouped_items.setdefault(item["set_code"], []).append(item)

    def fetch_group(group):
        set_code = group[0]["set_code"]
        lookup, cards_for_set = build_card_lookup_for_set(set_code)
        group_results = {}

        for item in group:
            key = make_lookup_key(item["name"], item["number"], item["set_code"])
            card = lookup.get(key)
            if card is None:
                card = resolve(cards_for_set, item["name"], item["number"], set_code)
            if card is None:
                card = resolve(find_fallback_cards(item, set_code), item["name"], item["number"], set_code)
            if card is None:
                group_results[key] = []
            else:
                group_results[key] = [card]

        return group_results

    with ThreadPoolExecutor(max_workers=max_workers) as ex:
        futures = [ex.submit(fetch_group, group) for group in grouped_items.values()]

        for f in as_completed(futures):
            results.update(f.result())

    return results

### Resolve the best matching card from the candidates (There is for sure a better way but this is good enough for now)
def resolve(cards, name, number, set_code):
    if not cards:
        return None

    target_name = norm(name)
    target_number = str(number).upper()
    target_aliases = set(build_name_aliases(name))

    best = None
    best_score = -999
    best_name_score = -1

    for c in cards:
        score = 0
        name_score = 0

        card_name = norm(c.name)
        card_number = str(c.number).upper()
        same_set = False
        card_aliases = set(build_name_aliases(c.name))

        # exact name
        if card_name == target_name:
            name_score = 100
            score += 100

        # alias overlap
        alias_overlap = len(target_aliases & card_aliases)
        if alias_overlap:
            name_score = max(name_score, 80 * alias_overlap)
            score += 80 * alias_overlap

        # partial name
        elif target_name in card_name or card_name in target_name:
            name_score = 50
            score += 50

        # exact number
        if card_number == target_number:
            score += 100
        elif target_number and card_number.endswith(target_number):
            score += 50

        # set similarity
        if hasattr(c, "set") and c.set:
            sid = c.set.id.lower()

            if set_code.lower() in sid:
                score += 50
                same_set = True

            if c.set.ptcgoCode:
                if c.set.ptcgoCode.upper() == set_code.upper():
                    score += 100
                    same_set = True

        if card_number == target_number and same_set:
            score += 150

        # prefer cards with images
        if hasattr(c, "images"):
            score += 5

        # only take candidates with some meaningful name signal; otherwise
        # a weak same-number/same-set hit can be a bad false positive.
        if name_score >= 50:
            if name_score > best_name_score or (name_score == best_name_score and score > best_score):
                best_name_score = name_score
                best_score = score
                best = c

    return best

### Build the list of image URLs based on the decklist
def build_image_list(deck_lines):
    unique, counts = build_unique(deck_lines)
    candidate_map = fetch_candidates(unique)

    images = []

    for key, item in unique.items():
        cards = candidate_map.get(key, [])

        card = resolve(cards, item["name"], item["number"], item["set_code"])

        if not card:
            print(f"Missing: {item['name']}")
            continue

        url = card.images.large
        images.extend([url] * counts[key])

    return images

### Layout and PDF generation functions
def get_layout_config(landscape_layout=False):
    if landscape_layout:
        return 4, 2
    return 3, 3

### Calculate the page size based on the number of columns and rows, including card gaps
def get_page_size(cols, rows, card_gap=0.25):
    width = cols * CARD_W + max(0, cols - 1) * card_gap
    height = rows * CARD_H + max(0, rows - 1) * card_gap
    return width, height

### Draw a grid for cutting guides
def draw_grid(c, x0, y0, cols, rows):
    c.setLineWidth(.5)
    c.setStrokeColor(colors.gray)
    c.setDash(1, 2)

    for i in range(1, cols):
        x = x0 + i * (CARD_W + CARD_GAP)
        c.line(x, y0, x, y0 + rows * (CARD_H + CARD_GAP))

    for j in range(1, rows):
        y = y0 + j * (CARD_H + CARD_GAP)
        c.line(x0, y, x0 + cols * (CARD_W + CARD_GAP), y)

    c.setDash()

### Generates a PDF with the card images laid out in a grid, ready for printing and cutting
def prefetch_images(image_urls, max_workers=12):
    unique_urls = list(dict.fromkeys(image_urls))
    with ThreadPoolExecutor(max_workers=max_workers) as ex:
        futures = [ex.submit(get_image, url) for url in unique_urls]
        for f in as_completed(futures):
            try:
                f.result()
            except:
                pass

### Create the PDF with the card images laid out in a grid
def create_pdf(image_urls, filename="proxies.pdf", landscape=False):
    cols, rows = get_layout_config(landscape)
    prefetch_images(image_urls)
    cards_per_page = cols * rows
    page_width, page_height = get_page_size(cols, rows, CARD_GAP)
    c = canvas.Canvas(
        filename,
        pagesize=(page_width, page_height),
        pageCompression=0
        )
    x0, y0 = 0, 0
    card_label = "Unofficial proxy. For personal use only."
    c.setFillColor(colors.gray)

    for page_start in range(0, len(image_urls), cards_per_page):
        c.setFont("Helvetica", CARD_LABEL_FONT_SIZE)
        page_urls = image_urls[page_start:page_start + cards_per_page]
        for offset, url in enumerate(page_urls):
            row = (offset // cols) % rows
            col = offset % cols
            reader = get_image_reader(url)

            x = col * (CARD_W + CARD_GAP)
            y = (rows - 1 - row) * (CARD_H + CARD_GAP)

            c.drawImage(
                reader,
                x, y,
                width=CARD_W,
                height=CARD_H,
                preserveAspectRatio=True,
                mask='auto'
            )
            c.setFont("Helvetica", CARD_LABEL_FONT_SIZE)
            c.drawCentredString(
                x + 3 * CARD_W / 4,
                y + 1,
                card_label
            )
        if page_start + cards_per_page < len(image_urls):
            c.showPage()
    if GRID_BOOL:   
        draw_grid(c, x0, y0, cols, rows)
    print("Done.")
    print("Created {} proxy cards across {} pages.".format(len(image_urls), c.getPageNumber()))
    c.save()

